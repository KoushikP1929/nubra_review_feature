/**
 * Nubra Trade Review — sample database setup.
 *
 * Run with: npm run db:setup
 *
 * Creates the positions / orders / executions schema in the Neon PostgreSQL
 * database and fills it with a clearly illustrative Indian-market sample
 * dataset (Aug / Sep / Oct 2026). October contains exactly 26 completed
 * positions (15 profitable, 11 losing) to match the approved UI reference.
 *
 * Sample-data shapes, agreed with the product owner:
 *  - SIMPLE POSITION: one entry order (limit) with one fill, one exit order
 *    (market) with one fill.
 *  - SCALED POSITION: two entry orders (both limit, both filled at the SAME
 *    price — the first adds units shortly after entry) plus one exit order.
 *    Because both fills share one price, P&L arithmetic stays exact:
 *    quantity × (exit price − entry price), minus fees.
 *  - Each position stores a PLANNED STOP (the trader's pre-set exit price).
 *    About a third of trades exit beyond their planned stop, which the
 *    app reports as an observable fact (never as a judgement).
 *
 * Realized P&L and fees are INGESTED FACTS computed here from raw prices at
 * data-generation time. Monthly aggregates (net P&L, win rate, average P&L,
 * cumulative totals, profit/loss counts) are NOT stored — the application
 * backend calculates those from the raw rows.
 *
 * All values are generated by a deterministic seeded RNG, so re-running the
 * script reproduces exactly the same sample months.
 */

import { neon } from "@neondatabase/serverless";

const sql = neon(process.env.DATABASE_URL);

const EXECUTION_FEE = 20;

// Sample instruments — Indian equities and index options (illustrative).
// moveMin/moveMax bound the per-unit price move (points) of a trade.
const INSTRUMENTS = [
  { name: "RELIANCE", type: "Equity", base: 1420.0, moveMin: 2, moveMax: 18 },
  { name: "HDFCBANK", type: "Equity", base: 1710.5, moveMin: 2, moveMax: 16 },
  { name: "INFY", type: "Equity", base: 1562.4, moveMin: 2, moveMax: 18 },
  { name: "TCS", type: "Equity", base: 3245.7, moveMin: 2, moveMax: 14 },
  { name: "ICICIBANK", type: "Equity", base: 1262.3, moveMin: 2, moveMax: 16 },
  { name: "SBIN", type: "Equity", base: 812.6, moveMin: 3, moveMax: 20 },
  { name: "TATAMOTORS", type: "Equity", base: 978.2, moveMin: 3, moveMax: 22 },
  { name: "WIPRO", type: "Equity", base: 291.4, moveMin: 3, moveMax: 14 },
  { name: "NIFTY 24500 CE", type: "Index Option", base: 186.2, moveMin: 10, moveMax: 40 },
  { name: "NIFTY 24300 PE", type: "Index Option", base: 141.8, moveMin: 10, moveMax: 40 },
  { name: "BANKNIFTY 52000 CE", type: "Index Option", base: 224.5, moveMin: 12, moveMax: 45 },
  { name: "BANKNIFTY 52000 PE", type: "Index Option", base: 168.9, moveMin: 12, moveMax: 45 },
];

const EQUITY_QTYS = [25, 30, 35, 40, 50, 60, 75, 100];
const OPTION_QTYS = [30, 45, 60, 75];

// Month plan: total completed trades and how many were profitable.
const MONTHS = [
  { ym: "202608", trades: 20, wins: 12 },
  { ym: "202609", trades: 22, wins: 13 },
  { ym: "202610", trades: 26, wins: 15 },
];

// Deterministic pseudo-random generator (mulberry32).
function seededRng(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

const round2 = (n) => Math.round(n * 100) / 100;
const pad2 = (n) => String(n).padStart(2, "0");

/** Business days (Mon–Fri) of a dashed month "YYYY-MM". */
function businessDays(ym) {
  const [y, m] = ym.split("-").map(Number);
  const out = [];
  for (let d = 1; d <= new Date(Date.UTC(y, m, 0)).getUTCDate(); d++) {
    const dow = new Date(Date.UTC(y, m - 1, d)).getUTCDay();
    if (dow !== 0 && dow !== 6) out.push(`${ym}-${pad2(d)}`);
  }
  return out;
}

function buildMonth(plan, seedBase) {
  const rng = seededRng(seedBase);
  // Trade outcome schedule shuffled deterministically.
  const schedule = [];
  for (let i = 0; i < plan.trades; i++) schedule.push(i < plan.wins);
  for (let i = schedule.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1));
    [schedule[i], schedule[j]] = [schedule[j], schedule[i]];
  }

  // plan.ym is the id-prefix form (e.g. "202610"); the calendar helpers
  // expect the dashed form ("2026-10").
  const days = businessDays(`${plan.ym.slice(0, 4)}-${plan.ym.slice(4)}`);
  const rows = [];
  for (let i = 0; i < plan.trades; i++) {
    const profitable = schedule[i];
    const inst = INSTRUMENTS[Math.floor(rng() * INSTRUMENTS.length)];
    const qty = (inst.type === "Equity" ? EQUITY_QTYS : OPTION_QTYS)[
      Math.floor(rng() * (inst.type === "Equity" ? EQUITY_QTYS.length : OPTION_QTYS.length))
    ];
    const dir = rng() < 0.7 ? "long" : "short";

    const floatStart = inst.moveMin + rng() * (inst.moveMax - inst.moveMin);
    const startPrice = round2(inst.base + (rng() - 0.5) * inst.moveMax * 2);
    const exitPrice =
      dir === "long"
        ? profitable
          ? round2(startPrice + floatStart)
          : round2(startPrice - floatStart)
        : profitable
          ? round2(startPrice - floatStart)
          : round2(startPrice + floatStart);

    // Planned stop: trader's pre-set exit level. stopFactor below 1 keeps
    // the stop between entry and exit; above 1 places the stop beyond the
    // recorded exit (an observable "exit beyond planned stop" trade).
    const stopFactor = 0.4 + rng() * 1.5;
    const plannedStop = round2(
      dir === "long"
        ? startPrice - Math.abs(exitPrice - startPrice) * stopFactor
        : startPrice + Math.abs(exitPrice - startPrice) * stopFactor,
    );

    // About half of positions receive one scale-in addition, filled at the
    // SAME price as the first entry so P&L math stays exact.
    const scaled = rng() < 0.45 && qty >= 30;
    const entryQty1 = scaled ? Math.ceil(qty / 2) : qty;
    const entryQty2 = scaled ? qty - entryQty1 : 0;

    const day = days[i % days.length];
    const entryHour = 4 + Math.floor(rng() * 5); // 04:00–08:59 UTC ≈ 9:30–14:30 IST
    const holdMin = 60 + Math.floor(rng() * 330); // 1–6.5 hours
    const entryDate = new Date(
      `${day}T${pad2(entryHour)}:${pad2(Math.floor(rng() * 60))}:${pad2(Math.floor(rng() * 60))}Z`,
    );
    const exitDate = new Date(entryDate.getTime() + holdMin * 60000);
    const entry = entryDate.toISOString().replace(".000Z", "Z");
    const exit = exitDate.toISOString().replace(".000Z", "Z");
    // Addition lands 15–40 minutes after the first fill, always before exit.
    const addDate = new Date(entryDate.getTime() + (15 + rng() * 25) * 60000);
    addDate.setTime(Math.min(addDate.getTime(), exitDate.getTime() - 5 * 60000));
    const added = addDate.toISOString().replace(".000Z", "Z");

    const fees = round2(EXECUTION_FEE * (scaled ? 3 : 2));
    const priceMove = qty * Math.abs(exitPrice - startPrice);

    rows.push({
      instrument: inst.name,
      instrumentType: inst.type,
      dir,
      qty,
      entryPrice: startPrice,
      exitPrice,
      plannedStop,
      scaled,
      entryQty1,
      entryQty2,
      entry,
      added,
      exit,
      pnl: round2(profitable ? priceMove - fees : -priceMove - fees),
    });
  }
  return rows;
}

async function main() {
  console.log("== Nubra Trade Review: sample database setup (Indian instruments) ==");
  console.log("Database:", process.env.DATABASE_URL.split("@")[1] || "(unknown)");
  console.log("");

  console.log("Recreating schema...");
  await sql`DROP TABLE IF EXISTS executions CASCADE`;
  await sql`DROP TABLE IF EXISTS orders CASCADE`;
  await sql`DROP TABLE IF EXISTS positions CASCADE`;

  await sql`
    CREATE TABLE positions (
      id              TEXT PRIMARY KEY,
      instrument      TEXT NOT NULL,
      instrument_type TEXT NOT NULL,
      side            TEXT NOT NULL CHECK (side IN ('long', 'short')),
      quantity        DOUBLE PRECISION NOT NULL CHECK (quantity > 0),
      status          TEXT NOT NULL CHECK (status IN ('closed')),
      opened_at       TIMESTAMPTZ NOT NULL,
      closed_at       TIMESTAMPTZ NOT NULL,
      planned_stop    DOUBLE PRECISION,
      realized_pnl    DOUBLE PRECISION NOT NULL,
      fees_total      DOUBLE PRECISION NOT NULL
    )
  `;
  await sql`
    CREATE TABLE orders (
      id          TEXT PRIMARY KEY,
      position_id TEXT NOT NULL REFERENCES positions (id) ON DELETE CASCADE,
      instrument  TEXT NOT NULL,
      side        TEXT NOT NULL CHECK (side IN ('buy', 'sell')),
      order_type  TEXT NOT NULL CHECK (order_type IN ('market', 'limit')),
      quantity    DOUBLE PRECISION NOT NULL CHECK (quantity > 0),
      status      TEXT NOT NULL CHECK (status IN ('filled')),
      created_at  TIMESTAMPTZ NOT NULL
    )
  `;
  await sql`
    CREATE TABLE executions (
      id          TEXT PRIMARY KEY,
      order_id    TEXT NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
      position_id TEXT NOT NULL REFERENCES positions (id) ON DELETE CASCADE,
      instrument  TEXT NOT NULL,
      side        TEXT NOT NULL CHECK (side IN ('buy', 'sell')),
      quantity    DOUBLE PRECISION NOT NULL CHECK (quantity > 0),
      price       DOUBLE PRECISION NOT NULL CHECK (price > 0),
      fees        DOUBLE PRECISION NOT NULL,
      executed_at TIMESTAMPTZ NOT NULL
    )
  `;
  await sql`CREATE INDEX idx_positions_closed_at ON positions (closed_at)`;
  await sql`CREATE INDEX idx_orders_position_id ON orders (position_id)`;
  await sql`CREATE INDEX idx_executions_position_id ON executions (position_id)`;
  console.log("Schema created: positions (incl. planned_stop), orders, executions");

  console.log("Generating and inserting illustrative trades...");
  let seed = 20261026;
  for (const plan of MONTHS) {
    const rows = buildMonth(plan, (seed += 7919));
    for (const [idx, row] of rows.entries()) {
      const pfx = `${plan.ym}_${pad2(idx + 1)}`;
      const posId = `pos_${pfx}`;
      const entryOrderId = `ord_${pfx}_entry`;
      const exitOrderId = `ord_${pfx}_exit`;
      const addOrderId = `ord_${pfx}_add`;
      const entrySide = row.dir === "long" ? "buy" : "sell";
      const exitSide = row.dir === "long" ? "sell" : "buy";

      await sql`
        INSERT INTO positions (id, instrument, instrument_type, side, quantity, status, opened_at, closed_at, planned_stop, realized_pnl, fees_total)
        VALUES (${posId}, ${row.instrument}, ${row.instrumentType}, ${row.dir}, ${row.qty}, 'closed', ${row.entry}, ${row.exit}, ${row.plannedStop}, ${row.pnl}, ${round2(EXECUTION_FEE * (row.scaled ? 3 : 2))})
      `;
      await sql`
        INSERT INTO orders (id, position_id, instrument, side, order_type, quantity, status, created_at)
        VALUES
          (${entryOrderId}, ${posId}, ${row.instrument}, ${entrySide}, 'limit', ${row.entryQty1}, 'filled', ${row.entry}),
          ${row.scaled ? sql`(${addOrderId}, ${posId}, ${row.instrument}, ${entrySide}, 'limit', ${row.entryQty2}, 'filled', ${row.added}),` : sql``}
          (${exitOrderId}, ${posId}, ${row.instrument}, ${exitSide}, 'market', ${row.qty}, 'filled', ${row.exit})
      `;
      await sql`
        INSERT INTO executions (id, order_id, position_id, instrument, side, quantity, price, fees, executed_at)
        VALUES
          (${`exec_${pfx}_entry`}, ${entryOrderId}, ${posId}, ${row.instrument}, ${entrySide}, ${row.entryQty1}, ${row.entryPrice}, ${EXECUTION_FEE}, ${row.entry}),
          ${row.scaled ? sql`(${`exec_${pfx}_add`}, ${addOrderId}, ${posId}, ${row.instrument}, ${entrySide}, ${row.entryQty2}, ${row.entryPrice}, ${EXECUTION_FEE}, ${row.added}),` : sql``}
          (${`exec_${pfx}_exit`}, ${exitOrderId}, ${posId}, ${row.instrument}, ${exitSide}, ${row.qty}, ${row.exitPrice}, ${EXECUTION_FEE}, ${row.exit})
      `;
    }

    const check = await sql.query(
      `SELECT COUNT(*) AS total, SUM(CASE WHEN realized_pnl > 0 THEN 1 ELSE 0 END) AS wins,
              SUM(CASE WHEN realized_pnl < 0 THEN 1 ELSE 0 END) AS losses
       FROM positions WHERE to_char(closed_at, 'YYYY-MM') = $1`,
      [`${plan.ym.slice(0, 4)}-${plan.ym.slice(4)}`],
    );
    const c = check[0];
    console.log(
      `  ${plan.ym}: ${c.total} trades (${c.wins} profitable, ${c.losses} losing)`,
    );
  }

  const extra = await sql.query(
    `SELECT (SELECT COUNT(*) FROM positions WHERE planned_stop IS NOT NULL) AS with_stop,
            (SELECT COUNT(*) FROM positions p WHERE (SELECT COUNT(*) FROM orders o WHERE o.position_id = p.id AND o.side IN ('buy','sell') AND o.order_type = 'limit') = 2) AS scaled_positions,
            CASE
              WHEN (SELECT COALESCE(SUM(1),0) FROM positions p, executions e
                    WHERE e.position_id = p.id AND e.side = (CASE WHEN p.side = 'long' THEN 'sell' ELSE 'buy' END)
                      AND ((p.side = 'long' AND e.price < p.planned_stop) OR (p.side = 'short' AND e.price > p.planned_stop))) > 0
              THEN 'yes' ELSE 'no' END AS stop_hits_present
  `,
  );
  console.log("Positions with planned stop:", extra[0].with_stop,
    "| positions with a scale-in addition:", extra[0].scaled_positions,
    "| stop-breach exits present:", extra[0].stop_hits_present);

  const counts = await sql`
    SELECT (SELECT count(*) FROM positions)  AS positions,
           (SELECT count(*) FROM orders)     AS orders,
           (SELECT count(*) FROM executions) AS executions
  `;
  console.log("\nRow counts:", counts[0]);
  console.log("Setup complete. Sample data is clearly illustrative (Aug/Sep/Oct 2026).");
}

main().catch((err) => {
  console.error("db:setup FAILED:", err.message || err);
  process.exit(1);
});
